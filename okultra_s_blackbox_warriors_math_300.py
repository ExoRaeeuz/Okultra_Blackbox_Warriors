"""### Conventions (agreed on week 1)

- Everything is float64, and no function changes its input (copy first).
- QR means the *reduced* version: A is m×n with m ≥ n, Q is m×n with orthonormal columns, R is n×n upper triangular.
- Q and R are only unique up to signs, so before comparing entries we flip signs to make diag(R) positive. Otherwise we just compare ‖A − QR‖.
- LU returns `P, L, U` with PA = LU, where P is a permutation matrix and L has 1s on the diagonal.
- Watch out: `scipy.linalg.lu` gives A = P L U instead, so our P is SciPy's P transposed. Easy to mix up.

## 2. Test matrices
"""

def exam_qr_matrix():
    # exam 2 Q3. first column is [3, 4, 0] so its norm is 5, nice for doing it by hand
    return np.array([[3., 5.], [4., 12.], [0., 13.]])

def exam_lu_matrix():
    # exam 2 Q2. the (1,1) entry is 0 so A = LU doesn't exist unless you pivot
    return np.array([[0., 1., 3.], [2., 3., 1.], [6., 9., 8.]])

def hilbert(n):
    # H[i,j] = 1/(i+j+1) with 0-based i, j. gets ill-conditioned fast, cond ~ e^(3.5n)
    i, j = np.indices((n, n))
    return 1.0 / (i + j + 1)

def random_matrix(m, n=None, rng=RNG):
    # gaussian entries, almost always well conditioned. square if n isn't given
    if n is None:
        n = m
    return rng.standard_normal((m, n))

def tiny_pivot(eps=1e-20):
    # [[eps, 1], [1, 1]]. no pivoting = dividing by eps, which wrecks everything
    return np.array([[eps, 1.], [1., 1.]])

def wilkinson_growth(n):
    # 1 on the diagonal, -1 below it, last column all 1s.
    # partial pivoting never swaps here and the last column doubles every step, so growth = 2^(n-1)
    A = np.eye(n) - np.tril(np.ones((n, n)), -1)
    A[:, -1] = 1.0
    return A

print("exam QR matrix:\n", exam_qr_matrix())
