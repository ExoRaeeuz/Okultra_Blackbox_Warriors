def validate_qr():
    print(f"{'method':<13}{'matrix':<16}{'recon':>10}{'||QtQ-I||':>12}{'R vs numpy':>12}  result")
    for name, fn in QR_METHODS.items():
        for label, A in QR_TESTS.items():
            out = try_run(fn, A)
            if out is None:
                print(f"{name:<13}{label:<16}  not implemented yet")
                break
            Q, R = normalize_qr(*out)
            _, R_ref = normalize_qr(*numpy_qr(A))
            rec = rel_recon_qr(A, Q, R)
            orth = orth_loss(Q)
            dR = np.linalg.norm(R - R_ref) / np.linalg.norm(R_ref)
            # don't compare R on hilbert, it's too ill-conditioned
            passed = rec < 1e-12 and ("hilbert" in label or dR < 1e-10)
            print(f"{name:<13}{label:<16}{rec:>10.1e}{orth:>12.1e}{dR:>12.1e}  {'pass' if passed else 'CHECK'}")

def validate_lu():
    print(f"{'method':<18}{'matrix':<16}{'recon':>10}{'P vs scipy':>12}{'growth':>9}  result")
    for name, fn in LU_METHODS.items():
        for label, A in LU_TESTS.items():
            out = try_run(fn, A)
            if out is None:
                print(f"{name:<18}{label:<16}  not implemented yet")
                break
            P, L, U = out
            P_ref = scipy_lu(A)[0]
            rec = rel_recon_lu(A, P, L, U)
            same_P = np.array_equal(P, P_ref)
            # L should be unit lower triangular and U upper triangular
            shapes_ok = np.allclose(np.diag(L), 1) and np.allclose(L, np.tril(L)) and np.allclose(U, np.triu(U))
            passed = rec < 1e-12 and shapes_ok
            print(f"{name:<18}{label:<16}{rec:>10.1e}{str(same_P):>12}{growth_factor(A, U):>9.2f}  {'pass' if passed else 'CHECK'}")

