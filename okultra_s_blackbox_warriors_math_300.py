"""### 8.2 Why pivoting matters: the tiny pivot matrix (Alan's bonus)
Solve Ax = b with A = [[ε, 1], [1, 1]]. The exact answer is basically [1, 1] and the matrix itself is well conditioned, so any big error here is the algorithm's fault.
"""

def solve_lu(P, L, U, b):
    # forward sub with L (unit diagonal), then back sub with U
    y = sla.solve_triangular(L, P @ b, lower=True, unit_diagonal=True)
    return sla.solve_triangular(U, y)

