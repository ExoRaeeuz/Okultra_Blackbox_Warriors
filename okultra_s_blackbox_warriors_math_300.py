"""## 3. Metrics"""

def rel_recon_qr(A, Q, R):
    # ||A - QR||_F / ||A||_F
    return np.linalg.norm(A - Q @ R) / np.linalg.norm(A)

def rel_recon_lu(A, P, L, U):
    # same idea for LU, but compare against PA
    return np.linalg.norm(P @ A - L @ U) / np.linalg.norm(A)

def orth_loss(Q):
    # how far Q is from having orthonormal columns (0 = perfect)
    I = np.eye(Q.shape[1])
    return np.linalg.norm(Q.T @ Q - I, 2)

def forward_error(x_hat, x_true):
    return np.linalg.norm(x_hat - x_true) / np.linalg.norm(x_true)

def cond2(A):
    return np.linalg.cond(A, 2)   # sigma_max / sigma_min

def growth_factor(A, U):
    # largest entry of U relative to the largest entry of A
    return np.abs(U).max() / np.abs(A).max()

def normalize_qr(Q, R):
    # QR is only unique up to signs, so flip columns of Q and rows of R until diag(R) > 0.
    # np.sign(0) is 0, so set those to +1 or we'd zero out a column
    signs = np.sign(np.diag(R)).copy()
    signs[signs == 0] = 1.0
    return Q * signs, R * signs[:, None]

"""## 4. Library baselines"""

def numpy_qr(A):
    # numpy calls LAPACK (dgeqrf + dorgqr), so this is Householder under the hood
    return np.linalg.qr(A, mode="reduced")

def scipy_lu(A):
    # LAPACK dgetrf with partial pivoting. scipy gives A = P_s L U and we want PA = LU, so P = P_s^T
    P_s, L, U = sla.lu(A)
    return P_s.T, L, U

