"""### 8.5 Timing vs. n (bonus)
The library versions are compiled LAPACK and ours are Python loops, so ours will be a lot slower. What we actually care about is the slope, since both should be O(n³).
"""

def best_time(fn, A, reps=3):
    # best of 3 so a random slow run doesn't mess up the plot
    best = None
    for _ in range(reps):
        t0 = time.perf_counter()
        fn(A)
        t = time.perf_counter() - t0
        if best is None or t < best:
            best = t
    return best

